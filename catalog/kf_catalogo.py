#!/usr/bin/env python3
"""Catálogo de edge cases (EC) e use cases (UC) do workflow: valida, gera os .md e mede a cobertura.

Fonte única: docs/catalogo.json. Cada entrada liga a um teste real (`ficheiro::nome`) ou fica `por cobrir`.

  kf_catalogo.py --check            estrutura válida e docs/edge-cases.md + docs/use-cases.md em dia (rc 0/1)
  kf_catalogo.py render             regenera os dois .md a partir do JSON
  kf_catalogo.py report [--json] [--no-run]
                                    corre os testes ligados e imprime cobertos/total; rc 0 só se EC >= limiar.ec
                                    e UC >= limiar.uc (por defeito 0,9 e 1,0); --no-run só conta ligações
Opções comuns: --file <catalogo.json> (defeito docs/catalogo.json) e --root <repo> (defeito: diretório atual).
"""
import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

POR_COBRIR = "por cobrir"
CAMPOS = {
    "edge_cases": ("id", "categoria", "gatilho", "esperado", "filho", "teste"),
    "use_cases": ("id", "objetivo", "comando", "resultado", "filho", "teste"),
}
PREFIXO = {"edge_cases": "EC", "use_cases": "UC"}
GERADO = "<!-- generated by catalog/kf_catalogo.py render from docs/catalogo.json: edit the JSON, not this file -->"


def _ref(ref):
    """Divide `caminho::[Classe::]nome` em (caminho, nome) ou devolve None se a forma for inválida."""
    if not isinstance(ref, str) or "::" not in ref:
        return None
    caminho, *resto = ref.split("::")
    nome = resto[-1].strip()
    p = Path(caminho)
    if (not nome or p.is_absolute() or ".." in p.parts or caminho.startswith(("/", "\\")) or ":" in caminho
            or any(parte.startswith("-") for parte in p.parts)):  # "-..." chegaria ao pytest/node como opção
        return None
    if p.suffix not in (".py", ".js"):
        return None
    return caminho, nome


def _nome_existe(ficheiro, nome, classe=None):
    """Python: função de topo (sem classe) ou método dentro do corpo de `classe`, para o node id do pytest existir."""
    texto = ficheiro.read_text(encoding="utf-8", errors="replace")
    if ficheiro.suffix == ".py":
        definicao = r"(?:async\s+)?def\s+" + re.escape(nome) + r"\s*\("
        if classe is None:
            return re.search(r"^" + definicao, texto, re.M) is not None
        m = re.search(r"^class\s+" + re.escape(classe) + r"\b[^\n]*:\s*\n((?:[ \t]+[^\n]*\n|[ \t]*\n)*)", texto + "\n", re.M)
        return m is not None and re.search(r"^[ \t]+" + definicao, m.group(1), re.M) is not None
    return any(q + nome + q in texto for q in ('"', "'", "`"))


def _problemas_id(secao, n, iid, vistos):
    """Problemas do ID do item `n` da secção (formato, duplicado, numeração)."""
    esperado = f"{PREFIXO[secao]}-{n:03d}"
    if not (isinstance(iid, str) and re.fullmatch(PREFIXO[secao] + r"-\d{3}", iid)):
        return [f"{iid}: ID mal formado (esperado {PREFIXO[secao]}-NNN)"]
    if iid in vistos:
        return [f"{iid}: ID duplicado"]
    if iid != esperado:
        return [f"{iid}: buraco ou ordem errada na numeração (esperado {esperado})"]
    return []


def _problemas_teste(iid, teste, root):
    """Problemas da referência `teste` de um item (forma, ficheiro, nome, EC/UC trocado)."""
    r = _ref(teste)
    if r is None:
        return [f"{iid}: teste '{teste}' fora da forma caminho/relativo.py|.js::nome"]
    if not (root / r[0]).is_file():
        return [f"{iid}: ficheiro de teste inexistente {r[0]}"]
    if not _nome_existe(root / r[0], r[1], (teste.split("::")[1:-1] or [None])[-1]):
        return [f"{iid}: teste '{r[1]}' não existe em {r[0]}"]
    m = re.search(r"(?i)(?:^|_)(ec|uc)_(\d{3})", r[1])
    outro = m and f"{m.group(1).upper()}-{m.group(2)}"
    if outro and isinstance(iid, str) and outro[:2] == iid[:2] and outro != iid:
        return [f"{iid}: teste '{r[1]}' tem o nome de {outro} (ligado ao EC/UC errado?)"]
    return []


def _problemas_item(secao, n, iid, item, campos, vistos, ids_cat, filhos, root):
    """Problemas de um item do catálogo (campos, categoria, filho, teste)."""
    probs = _problemas_id(secao, n, iid, vistos)
    for campo in campos[1:]:
        v = item.get(campo)
        if not (isinstance(v, str) and v.strip()):
            probs.append(f"{iid}: campo {campo} em falta ou vazio")
    if secao == "edge_cases" and item.get("categoria") and item["categoria"] not in ids_cat:
        probs.append(f"{iid}: categoria desconhecida {item['categoria']}")
    if item.get("filho") and filhos and item["filho"] not in filhos:
        probs.append(f"{iid}: filho desconhecido {item['filho']}")
    teste = item.get("teste")
    if isinstance(teste, str) and teste.strip() and teste != POR_COBRIR:
        probs += _problemas_teste(iid, teste, root)
    return probs


def _problemas_secao(secao, itens, campos, ids_cat, filhos, root):
    if not isinstance(itens, list) or not itens:
        return [f"{secao}: lista não vazia em falta"]
    probs, vistos = [], set()
    for n, item in enumerate(itens, 1):
        if not isinstance(item, dict):
            probs.append(f"{secao}[{n}]: tem de ser um objeto")
            continue
        iid = item.get("id", f"{secao}[{n}]")
        probs += _problemas_item(secao, n, iid, item, campos, vistos, ids_cat, filhos, root)
        vistos.add(iid)
    return probs


def problemas(cat, root):
    """Lista de problemas de estrutura (vazia = catálogo válido)."""
    root = Path(root)
    if not isinstance(cat, dict):
        return ["catálogo: o topo tem de ser um objeto JSON"]
    probs = []
    lim = cat.get("limiar")
    if not (isinstance(lim, dict) and all(isinstance(lim.get(k), (int, float)) and 0 <= lim[k] <= 1 for k in ("ec", "uc"))):
        probs.append("limiar: precisa de ec e uc entre 0 e 1")
    cats = cat.get("categorias")
    if not (isinstance(cats, list) and cats and all(isinstance(c, dict) and c.get("id") and c.get("titulo") for c in cats)):
        probs.append("categorias: lista não vazia de {id, titulo}")
        cats = []
    ids_cat = [c["id"] for c in cats]
    filhos = cat.get("filhos")
    if not (isinstance(filhos, list) and filhos and all(isinstance(f, str) and f for f in filhos)):
        probs.append("filhos: lista não vazia de nomes")
        filhos = []
    for secao, campos in CAMPOS.items():
        probs += _problemas_secao(secao, cat.get(secao), campos, ids_cat, filhos, root)
    for cid in ids_cat:
        if not any(isinstance(e, dict) and e.get("categoria") == cid for e in cat.get("edge_cases") or []):
            probs.append(f"categoria {cid}: vazia (sem EC)")
    return probs


def fracao(cobertos, total):
    return round(cobertos / total, 4) if total else 0.0


def medir(cat, resultados):
    """Conta cobertos (teste ligado e verde) por secção; `resultados` = {ref: passou}."""
    out = {}
    for secao, chave in (("edge_cases", "ec"), ("use_cases", "uc")):
        itens = cat.get(secao) or []
        em_falta = []
        for it in itens:
            t = it.get("teste")
            if t == POR_COBRIR or not t:
                em_falta.append({"id": it["id"], "motivo": POR_COBRIR})
            elif resultados.get(t) is not True:
                em_falta.append({"id": it["id"], "motivo": "falhou" if t in resultados else "sem correr"})
        cob = len(itens) - len(em_falta)
        out[chave] = {"total": len(itens), "cobertos": cob, "fracao": fracao(cob, len(itens)),
                      "limiar": cat["limiar"][chave], "em_falta": em_falta}
    out["ok"] = all(out[k]["fracao"] >= out[k]["limiar"] for k in ("ec", "uc"))
    return out


def _refs(cat):
    vistos = []
    for secao in CAMPOS:
        for it in cat.get(secao) or []:
            t = it.get("teste")
            if t and t != POR_COBRIR and t not in vistos:
                vistos.append(t)
    return vistos


def _correr_py(refs, root):
    if not refs:
        return {}
    ids = {r: r.replace("\\", "/") for r in refs}
    with tempfile.TemporaryDirectory() as tmp:
        xml = Path(tmp) / "r.xml"
        subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "-o", "junit_family=xunit2",
                        f"--junitxml={xml}", *ids.values()], cwd=root, capture_output=True, text=True)
        casos = {}  # (classname em partes, nome sem parâmetros) -> todos verdes
        if xml.is_file():
            import xml.etree.ElementTree as ET
            for tc in ET.parse(xml).iter("testcase"):
                chave = (tuple(tc.get("classname", "").split(".")), tc.get("name", "").split("[")[0])
                casos[chave] = casos.get(chave, True) and len(tc) == 0  # filho = failure, error ou skipped
    res = {}
    for r, nid in ids.items():
        caminho, *meio = nid.split("::")
        alvo = tuple(caminho[:-3].split("/")) + tuple(meio[:-1])
        achados = [ok for (p, n), ok in casos.items()
                   if n == meio[-1] and (p[-len(alvo):] == alvo or alvo[-len(p):] == p)]
        res[r] = bool(achados) and all(achados)
    return res


def _correr_js(ref, root):
    caminho, nome = _ref(ref)
    padrao = "^" + re.escape(nome) + "$"
    # sem --test: o ficheiro corre sozinho e só os testes selecionados contam em "# pass" (com --test o ficheiro conta como 1)
    r = subprocess.run(["node", "--test-reporter=tap", f"--test-name-pattern={padrao}", caminho], cwd=root,
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    m_pass = re.search(r"^# pass (\d+)", r.stdout, re.M)
    m_fail = re.search(r"^# fail (\d+)", r.stdout, re.M)
    return r.returncode == 0 and bool(m_pass) and int(m_pass.group(1)) >= 1 and bool(m_fail) and int(m_fail.group(1)) == 0


def correr_testes(refs, root):
    """Corre cada teste ligado e devolve {ref: passou}. Python numa só chamada ao pytest; JS um a um."""
    root = Path(root)
    py = [r for r in refs if _ref(r) and _ref(r)[0].endswith(".py")]
    res = _correr_py(py, root)
    for r in refs:
        if r not in res:
            res[r] = bool(_ref(r)) and _ref(r)[0].endswith(".js") and _correr_js(r, root)
    return res


def _cel(texto):
    return str(texto).replace("|", "\\|").replace("\n", " ")


def _teste_md(t):
    return f"`{POR_COBRIR}`" if t == POR_COBRIR else f"`{_cel(t)}`"


def render_edge_cases(cat):
    linhas = [
        "# Edge cases",
        "",
        GERADO,
        "",
        "Numbered catalogue of the ways a workflow run can stop half-way, fail or leave state inconsistent. "
        "Each case names the trigger, the expected behaviour (what state is kept and which command comes next), "
        f"the child story that owns it and the test that covers it, or `{POR_COBRIR}`. "
        "A case only counts as covered when its test exists and passes.",
        "",
        f"Measure with `kaizen catalog` (rc 0 only when EC coverage >= {cat['limiar']['ec']} and UC coverage >= {cat['limiar']['uc']}); "
        "validate with `kaizen catalog --check`; after editing `docs/catalogo.json` run `kaizen catalog render`. "
        "Use cases: [use-cases.md](use-cases.md).",
        "",
    ]
    lb = cat.get("linha_de_base")
    if isinstance(lb, dict):
        linhas += [
            "## Baseline",
            "",
            "| Date | EC covered | EC fraction | UC covered | UC fraction |",
            "|---|---|---|---|---|",
            f"| {lb.get('data', '')} | {lb.get('ec_cobertos', '')}/{lb.get('ec_total', '')} | {lb.get('ec_fracao', '')} "
            f"| {lb.get('uc_cobertos', '')}/{lb.get('uc_total', '')} | {lb.get('uc_fracao', '')} |",
            "",
        ]
    for c in cat["categorias"]:
        linhas += [f"## {c['titulo']}", "", "| ID | Trigger | Expected | Owner | Test |", "|---|---|---|---|---|"]
        for e in cat["edge_cases"]:
            if e.get("categoria") == c["id"]:
                linhas.append(f"| {e['id']} | {_cel(e['gatilho'])} | {_cel(e['esperado'])} | {_cel(e['filho'])} | {_teste_md(e['teste'])} |")
        linhas.append("")
    return "\n".join(linhas)


def render_use_cases(cat):
    linhas = [
        "# Use cases",
        "",
        GERADO,
        "",
        f"Each use case links to the test that runs it end to end, or `{POR_COBRIR}`. Edge cases: [edge-cases.md](edge-cases.md).",
        "",
        "| ID | I want to... | Run | You get | Test |",
        "|---|---|---|---|---|",
    ]
    for u in cat["use_cases"]:
        linhas.append(f"| {u['id']} | {_cel(u['objetivo'])} | {_cel(u['comando'])} | {_cel(u['resultado'])} | {_teste_md(u['teste'])} |")
    return "\n".join(linhas) + "\n"


def _alvos(ficheiro):
    docs = Path(ficheiro).parent
    return {docs / "edge-cases.md": render_edge_cases, docs / "use-cases.md": render_use_cases}


def _ler_md(p):
    return p.read_bytes().decode("utf-8").replace("\r\n", "\n") if p.is_file() else None


def _carregar(ficheiro):
    try:
        return json.loads(Path(ficheiro).read_text(encoding="utf-8"))
    except FileNotFoundError:
        print(f"erro: catálogo não encontrado: {ficheiro}", file=sys.stderr)
    except (json.JSONDecodeError, UnicodeDecodeError) as e:
        print(f"erro: catálogo ilegível ({ficheiro}): {e}", file=sys.stderr)
    return None


def _check(cat, ficheiro, root):
    probs = problemas(cat, root)
    if not probs:
        for p, fn in _alvos(ficheiro).items():
            if _ler_md(p) != fn(cat):
                probs.append(f"{p.name}: desatualizado face ao catálogo (correr: kaizen catalog render)")
    for p in probs:
        print(f"- {p}")
    n_ec, n_uc = len(cat.get("edge_cases") or []) if isinstance(cat, dict) else 0, len(cat.get("use_cases") or []) if isinstance(cat, dict) else 0
    print(f"catalog --check: {'ok' if not probs else f'{len(probs)} problema(s)'} ({n_ec} EC, {n_uc} UC)")
    return 0 if not probs else 1


def _render(cat, ficheiro, root):
    probs = problemas(cat, root)
    if probs:
        for p in probs:
            print(f"- {p}")
        print("render: catálogo inválido, nada escrito")
        return 1
    for p, fn in _alvos(ficheiro).items():
        novo = fn(cat)
        atual = p.read_bytes() if p.is_file() else None
        eol = b"\r\n" if atual and b"\r\n" in atual else b"\n"
        dados = novo.replace("\n", eol.decode()).encode("utf-8")
        if atual != dados:
            p.write_bytes(dados)
            print(f"render: {p.name} atualizado")
    return 0


def _report(cat, root, como_json, sem_correr):
    probs = problemas(cat, root)
    if probs:
        for p in probs:
            print(f"- {p}")
        print("report: catálogo inválido (corrigir com --check primeiro)")
        return 1
    refs = _refs(cat)
    res = {} if sem_correr else correr_testes(refs, root)
    if sem_correr:
        res = dict.fromkeys(refs, True)
    m = medir(cat, res)
    if como_json:
        print(json.dumps(m, ensure_ascii=False, indent=2))
        return 0 if m["ok"] else 1
    if sem_correr:
        print("report --no-run: testes ligados contados sem correr (cobertura real: kaizen catalog)")
    for chave in ("ec", "uc"):
        d = m[chave]
        estado = "ok" if d["fracao"] >= d["limiar"] else "abaixo"
        print(f"{chave.upper()}: {d['cobertos']}/{d['total']} cobertos ({d['fracao']:.2f}) · limiar {d['limiar']:.2f} · {estado}")
    for chave in ("ec", "uc"):
        falta = m[chave]["em_falta"]
        if falta:
            print(f"{chave.upper()} em falta: " + ", ".join(f"{f['id']} ({f['motivo']})" for f in falta))
    return 0 if m["ok"] else 1


def main(argv=None):
    for s in (sys.stdout, sys.stderr):
        if hasattr(s, "reconfigure"):
            s.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(prog="kaizen catalog", description="Catálogo EC/UC: validar, gerar e medir a cobertura.")
    ap.add_argument("acao", nargs="?", choices=("report", "render"), default="report")
    ap.add_argument("--check", action="store_true", help="validar estrutura e .md gerados")
    ap.add_argument("--json", action="store_true", help="report em JSON")
    ap.add_argument("--no-run", action="store_true", help="report sem correr os testes")
    ap.add_argument("--file", default=None, help="catálogo (defeito: <root>/docs/catalogo.json)")
    ap.add_argument("--root", default=".", help="raiz do repo (defeito: diretório atual)")
    a = ap.parse_args(argv)
    root = Path(a.root).resolve()
    ficheiro = Path(a.file) if a.file else root / "docs" / "catalogo.json"
    cat = _carregar(ficheiro)
    if cat is None:
        return 1
    if a.check:
        return _check(cat, ficheiro, root)
    if a.acao == "render":
        return _render(cat, ficheiro, root)
    return _report(cat, root, a.json, a.no_run)


if __name__ == "__main__":
    sys.exit(main())
